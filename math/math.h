#include <cmath>

namespace math{
    
    const inline float PI = 3.14159265358979323846f;
    inline float cos(float value){
        return std::cos(value);
    }
    
    inline float sin(float value){
        return std::sin(value);
    }
    
    inline float tan(float value){
        return std::tan(value);
    }

}